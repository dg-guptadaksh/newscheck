from psycopg import connect
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb


class PostgresHistory:
    def __init__(self, url):
        self.url = url

    def _connect(self):
        return connect(self.url, connect_timeout=8, row_factory=dict_row)

    def initialize(self):
        with self._connect() as connection:
            # Serialize schema creation when several instances cold-start together.
            connection.execute("SELECT pg_advisory_xact_lock(64823172)")
            connection.execute("""
                CREATE TABLE IF NOT EXISTS newscheck_screenings (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    session_id TEXT NOT NULL,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                    headline TEXT NOT NULL,
                    result JSONB NOT NULL
                )
            """)
            connection.execute("""
                CREATE INDEX IF NOT EXISTS newscheck_screenings_session_idx
                    ON newscheck_screenings (session_id, id DESC)
            """)

    def save(self, session, headline, result):
        with self._connect() as connection:
            return connection.execute(
                "INSERT INTO newscheck_screenings (session_id, headline, result) VALUES (%s, %s, %s) RETURNING id",
                (session, headline, Jsonb(result)),
            ).fetchone()["id"]

    def history(self, session):
        with self._connect() as connection:
            rows = connection.execute("""
                SELECT id, created_at, headline, result FROM newscheck_screenings
                WHERE session_id = %s ORDER BY id DESC LIMIT 50
            """, (session,)).fetchall()
        return [{**row, "created_at": row["created_at"].isoformat()} for row in rows]

    def clear(self, session):
        with self._connect() as connection:
            connection.execute("DELETE FROM newscheck_screenings WHERE session_id = %s", (session,))
